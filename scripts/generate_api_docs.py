"""Generates the Markdown pages of the API reference from the documentation comments of the sources.

Runs Doxygen with extras/docs/Doxyfile, which writes the declarations and their comments as XML, then
converts that XML to Markdown for the documentation website: one page per class, struct and enum,
pages for the constants, functions and type aliases declared directly in a namespace, and an index
linking them all. The layout follows the API reference of the Sideways Experiments Unity packages
(generated by SideXP.Instadoc), so both documentation websites read the same.
"""

