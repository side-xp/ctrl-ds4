@dataclass
class Page:
    """Page of the API reference, planned before any is rendered so they can link to each other."""

    # Path of the page, relative to the API reference folder.
    path: str
    # Title of the page: the name of the symbol, in its namespace (e.g. "Controller").
    title: str
    # Namespace of the symbol, empty for the global namespace.
    namespace: str
    # What the page documents: 'class' (or struct), 'enum', or 'members' of a namespace.
    kind: str
    # Element of the documented symbol (<compounddef> or <memberdef>), None for 'members' pages.
    element: Element | None = None
    # Members listed on the page, in declaration order.
    members: list[Element] = field(default_factory=list)
    # Id of the heading of each member or enum value, by Doxygen id.
    anchors: dict[str, str] = field(default_factory=dict)

    def add_anchor(self, refid: str, heading: str) -> str:
        """Gives a heading of the page a unique id.

        Args:
            refid: Doxygen id of the symbol of the heading.
            heading: Text of the heading.

        Returns:
            The id of the heading.
        """
        base_anchor = slugify(heading)
        anchor = base_anchor
        suffix = 2
        while anchor in self.anchors.values():
            anchor = f'{base_anchor}-{suffix}'
            suffix += 1
        self.anchors[refid] = anchor
        return anchor


def load_compounds(xml_dir: Path) -> list[Element]:
    """Loads the compounds (namespaces, classes...) written by Doxygen.

    Args:
        xml_dir: Folder of the Doxygen XML.

    Returns:
        The <compounddef> elements of the namespaces, classes, structs and unions.
    """
    index = ElementTree.parse(xml_dir / 'index.xml').getroot()
    compounds = []
    for entry in index.findall('compound'):
        if entry.get('kind') in COMPOUND_KINDS:
            document = ElementTree.parse(xml_dir / f'{entry.get("refid")}.xml').getroot()
            compounds.extend(document.findall('compounddef'))
    return compounds


def documented_members(element: Element) -> list[Element]:
    """Returns the members of a compound that the documentation shows, in declaration order.

    Args:
        element: The <compounddef> element.

    Returns:
        The public and protected <memberdef> elements.
    """
    return [
        member
        for section in element.findall('sectiondef')
        for member in section.findall('memberdef')
        if member.get('prot') in DOCUMENTED_PROTECTIONS
    ]


def summary(blocks: list[str]) -> str:
    """Returns the summary of a symbol for the index: the first paragraph of its description.

    Args:
        blocks: Blocks of the description.

    Returns:
        The summary, or an empty string if the first block isn't a paragraph.
    """
    if not blocks or blocks[0].startswith(('```', '!!!', '|', '**')):
        return ''
    return blocks[0].replace('\n', ' ')


class ApiReference:
    """API reference built from the Doxygen XML: its pages, and where each symbol is documented."""

    def __init__(self, xml_dir: Path):
        """Plans the pages of the API reference.

        Args:
            xml_dir: Folder of the Doxygen XML.
        """
        compounds = load_compounds(xml_dir)
        # Anonymous namespaces and classes are named "@0", "@1"...
        compounds = [compound for compound in compounds if '@' not in compound.findtext('compoundname')]
        self.namespaces = {
            compound.findtext('compoundname'): compound for compound in compounds if compound.get('kind') == 'namespace'
        }
        self.pages: list[Page] = []
        self.links: dict[str, Link] = {}

        for name, namespace in self.namespaces.items():
            self.plan_namespace(name, namespace)
        for compound in compounds:
            if compound.get('kind') != 'namespace':
                self.plan_class(compound)

    def add_page(self, name: str, namespace: str, kind: str, element: Element | None = None, file_name: str | None = None) -> Page:
        """Adds a page to the API reference.

        Args:
            name: Name of the symbol in its namespace (e.g. "Controller" or "Outer::Inner"), or
                title of a 'members' page.
            namespace: Namespace of the symbol.
            kind: What the page documents (see Page.kind).
            element: Element of the documented symbol, None for 'members' pages.
            file_name: Name of the page file without extension, None to derive it from the name.

        Returns:
            The page, in the folder of its namespace.
        """
        folder = namespace.replace('::', '.')
        if file_name is None:
            file_name = re.sub(r'[^A-Za-z0-9_.-]+', '-', name.replace('::', '.')).strip('-')
        path = posixpath.join(folder, f'{file_name}.md')
        if any(page.path == path for page in self.pages):
            raise ValueError(f'Two symbols of {namespace or "the global namespace"} would be documented on {path}')
        page = Page(path, name, namespace, kind, element)
        self.pages.append(page)
        if element is not None and kind != 'members':
            self.links[element.get('id')] = Link(path)
        return page

    def add_member(self, page: Page, member: Element) -> None:
        """Lists a member on a page.

        Args:
            page: Page to list the member on.
            member: The <memberdef> element of the member.
        """
        page.members.append(member)
        self.links[member.get('id')] = Link(page.path, page.add_anchor(member.get('id'), member_heading(member)))

    def namespace_of(self, qualified_name: str) -> str:
        """Returns the namespace of a symbol.

        Args:
            qualified_name: Name of the symbol, with its namespaces and classes (e.g. "A::B::C").

        Returns:
            The innermost known namespace that contains the symbol, empty for the global namespace.
        """
        namespaces = [namespace for namespace in self.namespaces if qualified_name.startswith(f'{namespace}::')]
        return max(namespaces, key=len, default='')

    def plan_namespace(self, name: str, namespace: Element) -> None:
        """Plans the pages of the enums, constants, functions and type aliases of a namespace.

        Args:
            name: Name of the namespace.
            namespace: The <compounddef> element of the namespace.
        """
        self.links[namespace.get('id')] = Link(INDEX_PAGE, slugify(name))
        members = documented_members(namespace)

        for member in members:
            if member.get('kind') == 'enum':
                self.plan_enum(member, name, '')

        variables = [member for member in members if member.get('kind') == 'variable']
        if variables:
            is_constant = all(member.get('constexpr') == 'yes' or flatten_line(member.find('type')).startswith('const ') for member in variables)
            page = self.add_page('Constants' if is_constant else 'Variables', name, 'members')
            for member in variables:
                self.add_member(page, member)

        for kind, title, file_name in (('function', 'Functions', 'Functions'), ('typedef', 'Type aliases', 'TypeAliases')):
            kind_members = [member for member in members if member.get('kind') == kind]
            if kind_members:
                page = self.add_page(title, name, 'members', file_name=file_name)
                for member in kind_members:
                    self.add_member(page, member)

    def plan_class(self, compound: Element) -> None:
        """Plans the page of a class, struct or union, and of its enums.

        Args:
            compound: The <compounddef> element of the class.
        """
        if compound.get('prot', 'public') not in DOCUMENTED_PROTECTIONS:
            return
        qualified_name = compound.findtext('compoundname')
        namespace = self.namespace_of(qualified_name)
        name = qualified_name[len(namespace) + 2 :] if namespace else qualified_name
        page = self.add_page(name, namespace, 'class', compound)

        for member in documented_members(compound):
            if member.get('kind') == 'enum':
                self.plan_enum(member, namespace, name)
            elif member.get('kind') in CLASS_MEMBER_KINDS:
                self.add_member(page, member)

    def plan_enum(self, enum: Element, namespace: str, scope: str) -> None:
        """Plans the page of an enum.

        Args:
            enum: The <memberdef> element of the enum.
            namespace: Namespace of the enum.
            scope: Name of the class that declares the enum, empty if it's declared in the namespace.
        """
        name = enum.findtext('name')
        page = self.add_page(f'{scope}::{name}' if scope else name, namespace, 'enum', enum)
        for enumerator in enum.findall('enumvalue'):
            self.links[enumerator.get('id')] = Link(page.path, page.add_anchor(enumerator.get('id'), enumerator.findtext('name')))

    def write(self, output_dir: Path) -> int:
        """Writes the pages of the API reference, replacing the previous ones.

        Args:
            output_dir: Folder of the API reference.

        Returns:
            Number of pages written, index included.
        """
        shutil.rmtree(output_dir, ignore_errors=True)
        contents_by_path = {page.path: self.render_page(page) for page in self.pages}
        contents_by_path[INDEX_PAGE] = self.render_index()
        for path, contents in contents_by_path.items():
            file = output_dir / path
            file.parent.mkdir(parents=True, exist_ok=True)
            # Same line endings on all platforms, so the pages don't depend on where they're built.
            file.write_text(contents, encoding='utf-8', newline='\n')
        return len(contents_by_path)

    def render_page(self, page: Page) -> str:
        """Renders a page of the API reference.

        Args:
            page: The page.

        Returns:
            The Markdown of the page.
        """
        renderer = DocRenderer(self.links, page.path)
        details = [f'Namespace: {code_span(page.namespace)}'] if page.namespace else []
        blocks = [f'# {escape_text(page.title)}']

        if page.kind == 'class':
            bases = [self.base_link(base, renderer) for base in page.element.findall('basecompoundref')]
            if bases:
                details.append(f'Inherits from: {", ".join(bases)}')
            signature = f'{template_prefix(page.element)}{page.element.get("kind")} {page.title}'
            base_declarations = [f'{base.get("prot")} {"virtual " if base.get("virt") == "virtual" else ""}{flatten_line(base)}' for base in page.element.findall('basecompoundref')]
            if base_declarations:
                signature += f' : {", ".join(base_declarations)}'
        elif page.kind == 'enum':
            signature = enum_signature(page.element)
        else:
            signature = None

        if details:
            blocks.append(f'> {" | ".join(details)}')
        if signature:
            blocks.append(code_fence(signature))
        if page.element is not None:
            description = renderer.describe(page.element.find('briefdescription'), page.element.find('detaileddescription'))
            blocks.extend(description.blocks + description.render_sections())

        if page.kind == 'class':
            blocks.extend(self.render_class_members(page, renderer))
        elif page.kind == 'enum':
            blocks.extend(self.render_enum_values(page, renderer))
        else:
            blocks.extend(self.render_member(member, page, renderer, 2) for member in page.members)
        return '\n\n'.join(blocks) + '\n'

    def base_link(self, base: Element, renderer: DocRenderer) -> str:
        """Returns the name of a base class, as a link if it's documented.

        Args:
            base: The <basecompoundref> element.
            renderer: Renderer of the page.

        Returns:
            The name of the base class, as inline code.
        """
        name = code_span(flatten_line(base))
        url = renderer.url(base.get('refid'))
        return f'[{name}]({url})' if url else name

    def render_class_members(self, page: Page, renderer: DocRenderer) -> list[str]:
        """Renders the members of a class, grouped by kind.

        Args:
            page: Page of the class.
            renderer: Renderer of the page.

        Returns:
            The Markdown blocks of the member groups.
        """
        class_name = page.title.split('::')[-1]
        groups = {'Type aliases': [], 'Constructors': [], 'Fields': [], 'Methods': []}
        for member in page.members:
            kind = member.get('kind')
            if kind == 'typedef':
                groups['Type aliases'].append(member)
            elif kind == 'variable':
                groups['Fields'].append(member)
            elif member.findtext('name') == class_name:
                groups['Constructors'].append(member)
            else:
                groups['Methods'].append(member)

        blocks = []
        for title, members in groups.items():
            if members:
                blocks.append(f'## {title}')
                blocks.extend(self.render_member(member, page, renderer, 3) for member in members)
        return blocks

    def render_enum_values(self, page: Page, renderer: DocRenderer) -> list[str]:
        """Renders the values of an enum.

        Args:
            page: Page of the enum.
            renderer: Renderer of the page.

        Returns:
            The Markdown blocks of the values.
        """
        blocks = ['## Values']
        for enumerator, declaration in enumerator_values(page.element):
            blocks.append(f'### {escape_text(enumerator.findtext("name"))}')
            blocks.append(f'<a id="{page.anchors[enumerator.get("id")]}"></a>')
            blocks.append(code_fence(declaration))
            description = renderer.describe(enumerator.find('briefdescription'), enumerator.find('detaileddescription'))
            blocks.extend(description.blocks + description.render_sections())
        return blocks

    def render_member(self, member: Element, page: Page, renderer: DocRenderer, level: int) -> str:
        """Renders a member: heading, declaration and description.

        Args:
            member: The <memberdef> element of the member.
            page: Page listing the member.
            renderer: Renderer of the page.
            level: Level of the heading of the member.

        Returns:
            The Markdown of the member.
        """
        description = renderer.describe(member.find('briefdescription'), member.find('detaileddescription'))
        blocks = [
            f'{"#" * level} {escape_text(member_heading(member))}',
            f'<a id="{page.anchors[member.get("id")]}"></a>',
            code_fence(member_signature(member)),
            *description.blocks,
            *description.render_sections(),
        ]
        return '\n\n'.join(blocks)

    def render_index(self) -> str:
        """Renders the index of the API reference, listing the pages of each namespace.

        Returns:
            The Markdown of the index.
        """
        renderer = DocRenderer(self.links, INDEX_PAGE)
        blocks = ['# API Reference']
        # The global namespace comes last, since a library usually declares everything in its own.
        namespaces = sorted({page.namespace for page in self.pages}, key=lambda name: (not name, name.lower()))

        for namespace in namespaces:
            blocks.append(f'## {escape_text(namespace)}' if namespace else '## Global namespace')
            blocks.append(f'<a id="{slugify(namespace) or "global-namespace"}"></a>')
            compound = self.namespaces.get(namespace)
            if compound is not None:
                blocks.extend(renderer.describe(compound.find('briefdescription'), compound.find('detaileddescription')).blocks)

            items = []
            for page in sorted((page for page in self.pages if page.namespace == namespace), key=lambda page: page.title.lower()):
                item = f'[{escape_text(page.title)}]({page.path})'
                if page.element is not None:
                    description = renderer.describe(page.element.find('briefdescription'), page.element.find('detaileddescription'))
                    page_summary = summary(description.blocks)
                    if page_summary:
                        item += f': {page_summary}'
                items.append(f'- {item}')
            blocks.append('\n'.join(items))
        return '\n\n'.join(blocks) + '\n'


def main() -> int:
    """Runs Doxygen, then converts its XML to the Markdown pages of the API reference."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--doxygen', default='doxygen', help='Doxygen executable, if not in your PATH (default: %(default)s)')
    args = parser.parse_args()

    doxygen = shutil.which(args.doxygen)
    if doxygen is None:
        print(f'{args.doxygen} not found, make sure Doxygen is installed and in your PATH (https://www.doxygen.nl/download.html)', file=sys.stderr)
        return 1

    # Removes the XML of the deleted or renamed sources, which Doxygen leaves behind.
    shutil.rmtree(XML_DIR, ignore_errors=True)
    if subprocess.run([doxygen, str(DOXYFILE)], cwd=ROOT_DIR).returncode != 0:
        return 1

    page_count = ApiReference(XML_DIR).write(OUTPUT_DIR)
    print(f'Wrote {page_count} page(s) to {OUTPUT_DIR.relative_to(ROOT_DIR).as_posix()}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
