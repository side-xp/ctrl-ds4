from dataclasses import dataclass, field
from pathlib import Path
from xml.etree.ElementTree import Element

ROOT_DIR = Path(__file__).resolve().parent.parent
DOXYFILE = ROOT_DIR / 'extras' / 'docs' / 'Doxyfile'
# Where Doxygen writes the XML, from OUTPUT_DIRECTORY in the Doxyfile.
XML_DIR = ROOT_DIR / 'build' / 'doxygen' / 'xml'
OUTPUT_DIR = ROOT_DIR / 'extras' / 'docs' / 'pages' / 'api'
INDEX_PAGE = 'index.md'

# Language of the code blocks that don't name theirs (with @code{.ext}): the sketches are C++.
DEFAULT_CODE_LANGUAGE = 'cpp'
# Extensions of @code{.ext} blocks that are C++ too, but that the syntax highlighter doesn't know.
CPP_CODE_EXTENSIONS = {'ino', 'h', 'hpp', 'cc', 'cxx'}
# Indentation of the blocks nested in a list item, as Python-Markdown (used by Zensical) expects.
LIST_INDENT = '    '

# Kinds of Doxygen compounds that hold documented symbols (files and folders only repeat them).
COMPOUND_KINDS = {'namespace', 'class', 'struct', 'union'}
# Protection levels of the documented members: the ones a sketch or a derived class can use.
DOCUMENTED_PROTECTIONS = {'public', 'protected'}
# Kinds of class members listed on the page of their class (enums get a page of their own).
CLASS_MEMBER_KINDS = {'typedef', 'function', 'variable'}

# Sections that follow the description of a symbol, in this order (as SideXP.Instadoc does).
SECTION_ORDER = ['Type parameters', 'Parameters', 'Returns', 'Exceptions', 'Remarks', 'See also']
# Section of each kind of parameter list (@tparam, @param, @throws and @retval).
PARAMETER_SECTIONS = {
    'templateparam': 'Type parameters',
    'param': 'Parameters',
    'exception': 'Exceptions',
    'retval': 'Returns',
}
# Section of the simple sections (@return, @remark...) that aren't shown as admonitions. The other
# kinds (@since, @pre...) get a section named after them.
SIMPLE_SECTIONS = {'return': 'Returns', 'remark': 'Remarks', 'see': 'See also'}
# Admonition type of the simple sections shown as admonitions (@note, @warning...).
ADMONITIONS = {'note': 'note', 'attention': 'warning', 'important': 'warning', 'warning': 'warning'}

# Characters that Doxygen writes as elements, mostly from the HTML entities of the comments.
SPECIAL_CHARACTERS = {
    'sp': ' ',
    'nonbreakablespace': ' ',
    'ndash': '–',
    'mdash': '—',
    'lsquo': '‘',
    'rsquo': '’',
    'ldquo': '“',
    'rdquo': '”',
    'copy': '©',
    'registered': '®',
    'trademark': '™',
}
# Elements of the comments with nothing to show on the website.
IGNORED_ELEMENTS = {'anchor', 'docbookonly', 'image', 'indexentry', 'latexonly', 'manonly', 'rtfonly', 'xmlonly'}
SECTION_ELEMENTS = {'sect1', 'sect2', 'sect3', 'sect4'}

# Characters of plain text that Markdown (with the extensions of the website) would interpret:
# emphasis, code, links, strikethrough, sub/superscript, math, highlight, and HTML tags.
MARKDOWN_CHARACTERS = re.compile(r'[\\`*\[\]~^$]|==|<(?=[A-Za-z/!?])|(?<![A-Za-z0-9])_|_(?![A-Za-z0-9])')
# Starts of a paragraph that Markdown would read as a heading, a quote or a list.
BLOCK_MARKERS = re.compile(r'^(?:[#>]|[-+*](?=\s)|\d+(?=\.\s))')


# --- Text helpers ---


def escape_text(text: str) -> str:
    """Escapes plain text, so Markdown shows it as is.

    Args:
        text: Text to escape.

    Returns:
        The escaped text.
    """

    def escape(match: re.Match) -> str:
        """Escapes a match of MARKDOWN_CHARACTERS."""
        characters = match.group(0)
        # Python-Markdown doesn't support escaping "<" with a backslash.
        if characters == '<':
            return '&lt;'
        return ''.join(f'\\{character}' for character in characters)

    return MARKDOWN_CHARACTERS.sub(escape, text)


def escape_block_start(text: str) -> str:
    """Escapes the start of a paragraph that Markdown would read as a heading, a quote or a list.

    Args:
        text: Paragraph to escape.

    Returns:
        The escaped paragraph.
    """
    match = BLOCK_MARKERS.match(text)
    if match is None:
        return text
    # A numbered list starts with a number and a dot: escaping the dot is enough.
    if match.group(0)[0].isdigit():
        return f'{match.group(0)}\\{text[match.end():]}'
    return f'\\{text}'


def flatten(element: Element | None) -> str:
    """Returns the text of an element and its children, without any markup.

    Args:
        element: Element to read, or None.

    Returns:
        The text of the element, or an empty string if it's None.
    """
    if element is None:
        return ''
    parts = [element.text or '']
    for child in element:
        parts.append(SPECIAL_CHARACTERS.get(child.tag, flatten(child)))
        parts.append(child.tail or '')
    return ''.join(parts)


def flatten_line(element: Element | None) -> str:
    """Returns the text of an element and its children on a single line, as in a declaration.

    Args:
        element: Element to read, or None.

    Returns:
        The text of the element, with its whitespace collapsed.
    """
    return ' '.join(flatten(element).split())


def slugify(text: str) -> str:
    """Returns the HTML id of a heading, in the format of SideXP.Instadoc.

    Args:
        text: Text of the heading (e.g. "bind(Button, uint8_t)").

    Returns:
        The id (e.g. "bind-button-uint8_t").
    """
    return re.sub(r'[^a-z0-9_]+', '-', text.lower()).strip('-')


def indent(text: str) -> str:
    """Indents the lines of a block to nest it in a list item or an admonition.

    Args:
        text: Block to indent.

    Returns:
        The indented block, with its blank lines left empty.
    """
    return '\n'.join(f'{LIST_INDENT}{line}' if line else '' for line in text.split('\n'))


def code_span(code: str) -> str:
    """Returns the Markdown of inline code.

    Args:
        code: Code to show.

    Returns:
        The code between enough backticks to contain the ones it includes.
    """
    longest_run = max((len(run) for run in re.findall(r'`+', code)), default=0)
    fence = '`' * (longest_run + 1)
    padding = ' ' if code.startswith('`') or code.endswith('`') else ''
    return f'{fence}{padding}{code}{padding}{fence}'


def code_fence(code: str, language: str = DEFAULT_CODE_LANGUAGE) -> str:
    """Returns the Markdown of a code block.

    Args:
        code: Code to show.
        language: Language of the code, for the syntax highlighting.

    Returns:
        The code between enough backticks to contain the ones it includes.
    """
    longest_run = max((len(run) for run in re.findall(r'`{3,}', code)), default=2)
    fence = '`' * (longest_run + 1)
    return f'{fence}{language}\n{code}\n{fence}'


def list_item(marker: str, blocks: list[str]) -> str:
    """Returns the Markdown of a list item.

    Args:
        marker: Marker of the item ("-" or "1.").
        blocks: Blocks of the item. The first one follows the marker, the next ones are nested.

    Returns:
        The list item.
    """
    first_block, *other_blocks = blocks or ['']
    first_line, *other_lines = first_block.split('\n')
    item = '\n'.join([f'{marker} {first_line}', *(indent(line) for line in other_lines)])
    return '\n\n'.join([item, *(indent(block) for block in other_blocks)])


def join_list_items(items: list[str]) -> str:
    """Joins list items into a list.

    Args:
        items: Items of the list, from list_item().

    Returns:
        The list, with blank lines between the items if one of them has several blocks.
    """
    has_nested_blocks = any('\n\n' in item for item in items)
    return ('\n\n' if has_nested_blocks else '\n').join(items)


def admonition(kind: str, title: str | None, blocks: list[str]) -> str:
    """Returns the Markdown of an admonition (a "note" or "warning" box).

    Args:
        kind: Type of the admonition (e.g. "note").
        title: Title of the admonition, or None for the default one.
        blocks: Contents of the admonition.

    Returns:
        The admonition.
    """
    header = f'!!! {kind} "{title}"' if title else f'!!! {kind}'
    if not blocks:
        return header
    body = indent('\n\n'.join(blocks))
    return f'{header}\n\n{body}'


# --- Declarations ---


def join_declaration(declared_type: str, name: str) -> str:
    """Joins a type and a name, as clang-format writes them.

    Args:
        declared_type: Type of the declaration, or an empty string (e.g. for a constructor).
        name: Name of the declaration.

    Returns:
        The declaration, with pointers and references stuck to the name (e.g. "const Type &name").
    """
    if not declared_type or not name:
        return declared_type or name
    if declared_type.endswith(('*', '&')):
        return f'{declared_type}{name}'
    return f'{declared_type} {name}'


def parameter_declaration(parameter: Element) -> str:
    """Returns the declaration of a function or template parameter.

    Args:
        parameter: The <param> element of the parameter.

    Returns:
        The declaration of the parameter, with its default value if any.
    """
    declaration = join_declaration(flatten_line(parameter.find('type')), flatten_line(parameter.find('declname')))
    declaration += flatten_line(parameter.find('array'))
    default_value = flatten_line(parameter.find('defval'))
    return f'{declaration} = {default_value}' if default_value else declaration


def template_prefix(element: Element) -> str:
    """Returns the template line of a declaration.

    Args:
        element: The compound or member element of the declaration.

    Returns:
        The template line followed by a line break, or an empty string if it's not a template.
    """
    template_parameters = element.find('templateparamlist')
    if template_parameters is None:
        return ''
    parameters = ', '.join(parameter_declaration(parameter) for parameter in template_parameters.findall('param'))
    return f'template <{parameters}>\n'


def specifiers(member: Element, declared_type: str) -> str:
    """Returns the specifiers (static, virtual...) that Doxygen keeps out of the type of a member.

    Args:
        member: The <memberdef> element of the member.
        declared_type: Type of the member, to skip the specifiers it already includes.

    Returns:
        The specifiers, each followed by a space.
    """
    arguments = member.findtext('argsstring') or ''
    names = []
    if member.get('static') == 'yes':
        names.append('static')
    # Overrides are marked as virtual, but the override specifier already tells it.
    if member.get('virt') in ('virtual', 'pure-virtual') and not re.search(r'\b(override|final)\b', arguments):
        names.append('virtual')
    if member.get('explicit') == 'yes':
        names.append('explicit')
    if member.get('constexpr') == 'yes':
        names.append('constexpr')
    return ''.join(f'{name} ' for name in names if name not in declared_type.split())


def function_suffix(member: Element) -> str:
    """Returns what follows the parameters of a function (const, override, = default...).

    Args:
        member: The <memberdef> element of the function.

    Returns:
        The suffix preceded by a space, or an empty string if there is none.
    """
    arguments = member.findtext('argsstring') or ''
    depth = 0
    for index, character in enumerate(arguments):
        if character == '(':
            depth += 1
        elif character == ')':
            depth -= 1
            if depth == 0:
                suffix = arguments[index + 1 :].strip()
                break
    else:
        return ''
    # "=0", "=default" or "=delete", which ends the declaration.
    definition_match = re.search(r'\s*=\s*(\w+)$', suffix)
    definition = f'= {definition_match.group(1)}' if definition_match else ''
    qualifiers = suffix[: definition_match.start()] if definition_match else suffix
    # Doxygen keeps noexcept out of the arguments, as attributes.
    if member.get('noexcept') == 'yes' and 'noexcept' not in qualifiers:
        expression = member.get('noexceptexpression', 'true')
        qualifiers += ' noexcept' if expression == 'true' else f' noexcept({expression})'
    suffix = ' '.join(part for part in (qualifiers.strip(), definition) if part)
    return f' {suffix}' if suffix else ''


def function_signature(member: Element) -> str:
    """Returns the declaration of a function.

    Args:
        member: The <memberdef> element of the function.

    Returns:
        The declaration, without the trailing semicolon.
    """
    declared_type = flatten_line(member.find('type'))
    parameters = ', '.join(parameter_declaration(parameter) for parameter in member.findall('param'))
    declaration = join_declaration(declared_type, member.findtext('name'))
    return f'{template_prefix(member)}{specifiers(member, declared_type)}{declaration}({parameters}){function_suffix(member)}'


def variable_signature(member: Element) -> str:
    """Returns the declaration of a variable or a constant.

    Args:
        member: The <memberdef> element of the variable.

    Returns:
        The declaration with its initializer, without the trailing semicolon.
    """
    declared_type = flatten_line(member.find('type'))
    declaration = join_declaration(declared_type, member.findtext('name'))
    declaration += flatten_line(member.find('argsstring'))
    initializer = flatten_line(member.find('initializer'))
    if initializer:
        # Either "= value" or a braced initializer ("{value}").
        declaration += f' {initializer}' if initializer.startswith('=') else initializer
    return f'{template_prefix(member)}{specifiers(member, declared_type)}{declaration}'


def typedef_signature(member: Element) -> str:
    """Returns the declaration of a type alias (using or typedef).

    Args:
        member: The <memberdef> element of the type alias.

    Returns:
        The declaration, without the trailing semicolon.
    """
    name = member.findtext('name')
    definition = flatten_line(member.find('definition'))
    if definition.startswith('using '):
        # The definition is the declaration as written, only with the qualified name.
        return f'{template_prefix(member)}{definition.replace(member.findtext("qualifiedname") or "", name, 1)}'

    declared_type = flatten_line(member.find('type'))
    arguments = flatten_line(member.find('argsstring'))
    # Doxygen splits the function pointers around their name: "void(*)" and "(int code)".
    pointer_match = re.fullmatch(r'(.*\(\s*[*&])\s*\)', declared_type)
    if pointer_match:
        return f'typedef {pointer_match.group(1)}{name}){arguments}'
    return f'typedef {join_declaration(declared_type, name)}{arguments}'


def enum_signature(member: Element) -> str:
    """Returns the declaration of an enum.

    Args:
        member: The <memberdef> element of the enum.

    Returns:
        The declaration, with the underlying type if any.
    """
    keyword = 'enum class' if member.get('strong') == 'yes' else 'enum'
    underlying_type = flatten_line(member.find('type'))
    declaration = f'{keyword} {member.findtext("name")}'
    return f'{declaration} : {underlying_type}' if underlying_type else declaration


def member_signature(member: Element) -> str:
    """Returns the declaration of a member.

    Args:
        member: The <memberdef> element of the member.

    Returns:
        The declaration, preceded by "protected:" if the member is protected.
    """
    signatures = {
        'function': function_signature,
        'variable': variable_signature,
        'typedef': typedef_signature,
        'enum': enum_signature,
    }
    signature = signatures[member.get('kind')](member)
    return f'protected:\n{signature}' if member.get('prot') == 'protected' else signature


def member_heading(member: Element) -> str:
    """Returns the heading of a member: its name, followed by its parameter types for a function.

    Args:
        member: The <memberdef> element of the member.

    Returns:
        The heading (e.g. "bind(Button, uint8_t, ButtonWiring)").
    """
    name = member.findtext('name')
    if member.get('kind') != 'function':
        return name
    parameter_types = ', '.join(flatten_line(parameter.find('type')) for parameter in member.findall('param'))
    return f'{name}({parameter_types})'


def enumerator_values(enum: Element) -> list[tuple[Element, str]]:
    """Returns the values of an enum, with their declarations.

    Args:
        enum: The <memberdef> element of the enum.

    Returns:
        Each <enumvalue> element, with its declaration (e.g. "Cross = 0"). The value is computed
        when it's implicit, unless it follows a value that isn't a plain integer.
    """
    values = []
    next_value: int | None = 0
    for enumerator in enum.findall('enumvalue'):
        name = enumerator.findtext('name')
        initializer = flatten_line(enumerator.find('initializer')).lstrip('=').strip()
        if initializer:
            try:
                value = int(initializer, 0)
            except ValueError:
                value = None
            declaration = f'{name} = {initializer}'
        else:
            value = next_value
            declaration = name if value is None else f'{name} = {value}'
        values.append((enumerator, declaration))
        next_value = None if value is None else value + 1
    return values


# --- Documentation comments ---


@dataclass
class Description:
    """Documentation of a symbol, split the way its page shows it."""

    # Markdown blocks of the description itself.
    blocks: list[str] = field(default_factory=list)
    # Markdown blocks of each section that follows the description (e.g. "Parameters").
    sections: dict[str, list[str]] = field(default_factory=dict)

    def add_section(self, label: str, blocks: list[str]) -> None:
        """Adds blocks to a section, creating it if needed.

        Args:
            label: Name of the section (e.g. "Returns").
            blocks: Blocks to add.
        """
        self.sections.setdefault(label, []).extend(blocks)

    def render_sections(self) -> list[str]:
        """Returns the blocks of the sections, each preceded by its name in bold.

        Returns:
            The blocks, with the sections of SECTION_ORDER first, in that order.
        """
        labels = [label for label in SECTION_ORDER if label in self.sections]
        labels += [label for label in self.sections if label not in SECTION_ORDER]
        blocks = []
        for label in labels:
            blocks.append(f'**{label}**')
            blocks.extend(self.sections[label])
        return blocks


@dataclass
class Link:
    """Where a symbol is documented in the API reference."""

    # Path of the page, relative to the API reference folder.
    page: str
    # Id of the heading of the symbol on the page, or None for the page itself.
    anchor: str | None = None


class DocRenderer:
    """Converts the documentation comments of the Doxygen XML to Markdown, for a given page."""

    def __init__(self, links: dict[str, Link], page_path: str):
        """Creates a renderer for a page.

        Args:
            links: Where each symbol is documented, by Doxygen id.
            page_path: Path of the rendered page, relative to the API reference folder, from which
                the links are written.
        """
        self.links = links
        self.page_path = page_path

    def describe(self, *elements: Element | None) -> Description:
        """Converts description elements to Markdown.

        Args:
            elements: Description elements (e.g. <briefdescription> and <detaileddescription>),
                or None for the missing ones.

        Returns:
            The description, made of the contents of all the elements.
        """
        description = Description()
        for element in elements:
            if element is not None:
                self.add_contents(element, description)
        return description

    def nested_blocks(self, element: Element | None) -> list[str]:
        """Converts the contents of an element to Markdown blocks, sections included.

        Args:
            element: Element containing paragraphs (e.g. <listitem>), or None.

        Returns:
            The blocks.
        """
        description = self.describe(element)
        return description.blocks + description.render_sections()

    def add_contents(self, element: Element, description: Description) -> None:
        """Adds the paragraphs and sections of an element to a description.

        Args:
            element: Element containing paragraphs.
            description: Description to add them to.
        """
        for child in element:
            if child.tag == 'para':
                self.add_para(child, description)
            elif child.tag in SECTION_ELEMENTS:
                title = child.find('title')
                if title is not None:
                    description.blocks.append(f'**{self.inline(title).strip()}**')
                self.add_contents(child, description)
            # The other elements are titles (already handled) and @internal blocks (hidden).

    def add_para(self, para: Element, description: Description) -> None:
        """Adds a paragraph to a description, splitting it around the blocks it contains.

        Doxygen puts the code blocks, lists and sections of a comment inside its paragraphs, which
        Markdown can't do.

        Args:
            para: The <para> element.
            description: Description to add it to.
        """
        parts = [self.text(para.text)]

        def flush() -> None:
            """Adds the inline text read so far as a paragraph."""
            paragraph = ''.join(parts).strip()
            if paragraph:
                description.blocks.append(escape_block_start(re.sub(r' {2,}', ' ', paragraph)))
            parts.clear()

        for child in para:
            if not self.add_block(child, description, flush):
                parts.append(self.inline_element(child))
            parts.append(self.text(child.tail))
        flush()

    def add_block(self, element: Element, description: Description, flush) -> bool:
        """Adds an element to a description if it's a block, after the inline text read before it.

        Args:
            element: Child element of a paragraph.
            description: Description to add it to.
            flush: Function adding the inline text read so far as a paragraph.

        Returns:
            True if the element is a block and was added, False if it's inline.
        """
        tag = element.tag
        if tag == 'programlisting':
            flush()
            description.blocks.append(self.code_block(element))
        elif tag in ('verbatim', 'preformatted'):
            flush()
            description.blocks.append(code_fence(flatten(element).strip('\n'), 'text'))
        elif tag in ('itemizedlist', 'orderedlist'):
            flush()
            description.blocks.append(self.list_block(element, tag == 'orderedlist'))
        elif tag == 'simplesect':
            flush()
            self.add_simple_section(element, description)
        elif tag == 'parameterlist':
            flush()
            self.add_parameters(element, description)
        elif tag == 'xrefsect':
            flush()
            title = flatten_line(element.find('xreftitle'))
            kind = 'warning' if title.lower() == 'deprecated' else 'note'
            description.blocks.append(admonition(kind, title, self.nested_blocks(element.find('xrefdescription'))))
        elif tag == 'blockquote':
            flush()
            quote = '\n\n'.join(self.nested_blocks(element))
            description.blocks.append('\n'.join(f'> {line}' if line else '>' for line in quote.split('\n')))
        elif tag == 'table':
            flush()
            description.blocks.append(self.table(element))
        elif tag == 'heading':
            flush()
            description.blocks.append(f'**{self.inline(element).strip()}**')
        elif tag == 'hruler':
            flush()
        else:
            return False
        return True

    def add_simple_section(self, section: Element, description: Description) -> None:
        """Adds a simple section (@return, @note, @see...) to a description.

        Args:
            section: The <simplesect> element.
            description: Description to add it to.
        """
        kind = section.get('kind')
        blocks = self.nested_blocks(section)
        if kind == 'par':
            title = section.find('title')
            if title is not None:
                description.blocks.append(f'**{self.inline(title).strip()}**')
            description.blocks.extend(blocks)
        elif kind in ADMONITIONS:
            description.blocks.append(admonition(ADMONITIONS[kind], None, blocks))
        elif kind == 'see':
            description.add_section('See also', [join_list_items([list_item('-', [block]) for block in blocks])])
        else:
            description.add_section(SIMPLE_SECTIONS.get(kind, kind.capitalize()), blocks)

    def add_parameters(self, parameter_list: Element, description: Description) -> None:
        """Adds a parameter list (@param, @tparam, @throws or @retval) to a description.

        Args:
            parameter_list: The <parameterlist> element.
            description: Description to add it to.
        """
        items = []
        for parameter in parameter_list.findall('parameteritem'):
            names = ', '.join(code_span(flatten_line(name)) for name in parameter.iter('parametername'))
            blocks = self.nested_blocks(parameter.find('parameterdescription'))
            if blocks:
                blocks[0] = f'{names}: {blocks[0]}'
            items.append(list_item('-', blocks or [names]))
        label = PARAMETER_SECTIONS.get(parameter_list.get('kind'), 'Parameters')
        description.add_section(label, [join_list_items(items)])

    def code_block(self, listing: Element) -> str:
        """Converts a code block (@code) to Markdown.

        Args:
            listing: The <programlisting> element.

        Returns:
            The code block.
        """
        extension = (listing.get('filename') or '').lstrip('.')
        is_cpp = not extension or extension in CPP_CODE_EXTENSIONS
        lines = [flatten(line).rstrip() for line in listing.findall('codeline')]
        return code_fence('\n'.join(lines).strip('\n'), DEFAULT_CODE_LANGUAGE if is_cpp else extension)

    def list_block(self, element: Element, is_ordered: bool) -> str:
        """Converts a list to Markdown.

        Args:
            element: The <itemizedlist> or <orderedlist> element.
            is_ordered: True for a numbered list, False for a bulleted one.

        Returns:
            The list.
        """
        items = []
        for number, item in enumerate(element.findall('listitem'), start=1):
            items.append(list_item(f'{number}.' if is_ordered else '-', self.nested_blocks(item)))
        return join_list_items(items)

    def table(self, element: Element) -> str:
        """Converts a table to Markdown. The first row is the header.

        Args:
            element: The <table> element.

        Returns:
            The table, with the blocks of each cell on a single line.
        """
        rows = []
        for row in element.findall('row'):
            cells = [' <br> '.join(self.nested_blocks(entry)).replace('\n', ' ').replace('|', '\\|') for entry in row.findall('entry')]
            rows.append(cells)
        if not rows:
            return ''
        separator = ['---'] * len(rows[0])
        return '\n'.join(f'| {" | ".join(cells)} |' for cells in [rows[0], separator, *rows[1:]])

    def inline(self, element: Element) -> str:
        """Converts the contents of an element to inline Markdown.

        Args:
            element: Element containing text and inline elements.

        Returns:
            The Markdown of the contents, without the element itself.
        """
        parts = [self.text(element.text)]
        for child in element:
            parts.append(self.inline_element(child))
            parts.append(self.text(child.tail))
        return ''.join(parts)

    def inline_element(self, element: Element) -> str:
        """Converts an inline element (link, emphasis, inline code...) to Markdown.

        Args:
            element: The element.

        Returns:
            The Markdown of the element.
        """
        tag = element.tag
        if tag == 'ref':
            return self.reference(element)
        if tag == 'computeroutput':
            return self.inline_code(element)
        if tag == 'emphasis':
            return self.wrap(element, '*')
        if tag == 'bold':
            return self.wrap(element, '**')
        if tag in ('s', 'strike', 'del'):
            return self.wrap(element, '~~')
        if tag == 'ulink':
            return f'[{self.inline(element).strip()}]({element.get("url")})'
        if tag == 'linebreak':
            return '<br>'
        if tag in ('htmlonly', 'formula'):
            return element.text or ''
        if tag in SPECIAL_CHARACTERS:
            return SPECIAL_CHARACTERS[tag]
        if tag in IGNORED_ELEMENTS:
            return ''
        return self.inline(element)

    def wrap(self, element: Element, marker: str) -> str:
        """Converts the contents of an element to inline Markdown, between emphasis markers.

        Args:
            element: The element.
            marker: Markers to put around the contents (e.g. "**" for bold).

        Returns:
            The wrapped contents, or an empty string if there are none.
        """
        contents = self.inline(element).strip()
        return f'{marker}{contents}{marker}' if contents else ''

    def reference(self, element: Element) -> str:
        """Converts a reference to a symbol to a link.

        Args:
            element: The <ref> element.

        Returns:
            The link, or the plain name of the symbol if it isn't documented (e.g. internal ones).
        """
        name = escape_text(flatten(element))
        url = self.url(element.get('refid'))
        return f'[{name}]({url})' if url else name

    def inline_code(self, element: Element) -> str:
        """Converts inline code (`code` or @c) to Markdown.

        Args:
            element: The <computeroutput> element.

        Returns:
            The inline code, as a link if it's only a reference to a documented symbol.
        """
        children = list(element)
        code = code_span(flatten(element))
        is_reference = len(children) == 1 and children[0].tag == 'ref' and not (element.text or '').strip() and not (children[0].tail or '').strip()
        url = self.url(children[0].get('refid')) if is_reference else None
        return f'[{code}]({url})' if url else code

    def text(self, text: str | None) -> str:
        """Converts plain text to Markdown.

        Args:
            text: Text from the XML, or None.

        Returns:
            The text with its whitespace collapsed (Doxygen keeps the line breaks of the comments),
            escaped.
        """
        return escape_text(re.sub(r'\s+', ' ', text)) if text else ''

    def url(self, refid: str | None) -> str | None:
        """Returns the URL of the documentation of a symbol, relative to the rendered page.

        Args:
            refid: Doxygen id of the symbol, or None.

        Returns:
            The URL, or None if the symbol isn't documented.
        """
        link = self.links.get(refid)
        if link is None:
            return None
        if link.page == self.page_path:
            path = '' if link.anchor else posixpath.basename(link.page)
        else:
            path = posixpath.relpath(link.page, posixpath.dirname(self.page_path) or '.')
        return f'{path}#{link.anchor}' if link.anchor else path


